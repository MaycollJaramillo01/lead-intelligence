const campaigns = campaignFixture as CampaignPage;
const catalog = catalogFixture as ScoringCatalog;
const [profile] = catalog.icp_profiles;
const page = pageFixture as ExplorerPage;

async function renderHistory(folderName: string | null = "Other searches") {
  render(
    <MemoryRouter initialEntries={["/mis-busquedas"]}>
      <Routes>
        <Route path="/mis-busquedas" element={<ClientSearchesScreen />} />
        <Route path="/buscar-clientes" element={<ClientSearchScreen />} />
      </Routes>
    </MemoryRouter>,
  );
  if (folderName) {
    await userEvent.click(
      await screen.findByRole("button", { name: new RegExp(`^${folderName} ·`) }),
    );
  }
}

