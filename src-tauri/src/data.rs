/// Lower-case hyphenated UUID, as generated by the worker (UUIDv7).
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize)]
#[serde(transparent)]
pub struct Id(String);

impl Id {
    pub fn parse(text: &str) -> Result<Self, String> {
        let uuid = Uuid::parse_str(text).map_err(|e| format!("invalid id {text:?}: {e}"))?;
        let canonical = uuid.hyphenated().to_string();
        if canonical != text {
            return Err(format!("id {text:?} is not in canonical lower-case form"));
        }
        Ok(Self(canonical))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for Id {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl<'de> Deserialize<'de> for Id {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        Self::parse(&String::deserialize(deserializer)?).map_err(D::Error::custom)
    }
}

/// Contract timestamp: UTC with milliseconds (`2026-01-01T00:00:00.000Z`). Kept as validated text
/// so it round-trips byte for byte; chrono alone would print `...:00Z` for a whole second.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize)]
#[serde(transparent)]
pub struct UtcTimestamp(String);

impl UtcTimestamp {
    pub fn parse(text: &str) -> Result<Self, String> {
        let parsed = DateTime::parse_from_rfc3339(text)
            .map_err(|e| format!("invalid timestamp {text:?}: {e}"))?;
        let canonical = parsed
            .with_timezone(&Utc)
            .format("%Y-%m-%dT%H:%M:%S%.3fZ")
            .to_string();
        if canonical != text {
            return Err(format!(
                "timestamp {text:?} is not UTC with milliseconds (expected {canonical})"
            ));
        }
        Ok(Self(canonical))
    }
}

impl<'de> Deserialize<'de> for UtcTimestamp {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        Self::parse(&String::deserialize(deserializer)?).map_err(D::Error::custom)
    }
}

/// A probability in `[0, 1]`.
#[derive(Debug, Clone, Copy, PartialEq, Serialize)]
#[serde(transparent)]
pub struct Confidence(f64);

impl<'de> Deserialize<'de> for Confidence {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let value = f64::deserialize(deserializer)?;
        if !(0.0..=1.0).contains(&value) {
            return Err(D::Error::custom(format!(
                "confidence {value} is outside [0, 1]"
            )));
        }
        Ok(Self(value))
    }
}

/// Opaque keyset cursor: URL-safe base64 produced by the worker.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(transparent)]
pub struct Cursor(String);

impl<'de> Deserialize<'de> for Cursor {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let text = String::deserialize(deserializer)?;
        let valid = (1..=MAX_CURSOR_LEN).contains(&text.len())
            && text
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_');
        if !valid {
            return Err(D::Error::custom("malformed cursor"));
        }
        Ok(Self(text))
    }
}

