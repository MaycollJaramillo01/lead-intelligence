//! Data contract (records, queries and pages), mirrored from
//! `services/research-engine/src/research_engine/domain.py`, the source of truth. Only the shapes
//! that cross the IPC boundary are mirrored. `tests/contracts.rs` round-trips the generated
//! fixtures through these types, so any drift fails the test suite.
//!
//! Nothing is trusted: unknown fields, unknown enumeration values, malformed ids and timestamps are
//! rejected while deserialising, and every page the worker returns is checked against the query
//! that produced it before it reaches the UI.

