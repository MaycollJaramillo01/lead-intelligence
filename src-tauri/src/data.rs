fn check_page(len: usize, total: u64, has_more: bool, limit: u32) -> Result<(), String> {
    if len > limit as usize {
        return Err(format!("page has {len} rows but the limit was {limit}"));
    }
    if (len as u64) > total {
        return Err(format!(
            "page has {len} rows but reports a total of {total}"
        ));
    }
    if has_more && len < limit as usize {
        return Err("a partial page cannot have a next cursor".into());
    }
    Ok(())
}

impl BusinessPage {
    /// Checks the worker's answer against the query that produced it.
    pub fn validate(&self, query: &BusinessListQuery) -> Result<(), String> {
        check_page(
            self.items.len(),
            self.total,
            self.next_cursor.is_some(),
            query.limit,
        )?;
        if let Some(project) = &query.project_id
            && let Some(other) = self.items.iter().find(|item| &item.project_id != project)
        {
            return Err(format!("business {} belongs to another project", other.id));
        }
        match query.status {
            Some(status) if self.items.iter().any(|item| item.status != status) => {
                Err("page contains businesses outside the status filter".into())
            }
            _ => Ok(()),
        }
    }
}

impl DatasetPage {
    pub fn validate(&self, query: &DatasetListQuery) -> Result<(), String> {
        check_page(
            self.items.len(),
            self.total,
            self.next_cursor.is_some(),
            query.limit,
        )
    }
}

fn check_observations<T: Observation>(business: &Id, group: &[Observed<T>]) -> Result<(), String> {
    for observed in group {
        if observed.value.business_id() != business {
            return Err(format!(
                "an observation of business {} was returned for {business}",
                observed.value.business_id()
            ));
        }
        if observed.value.extraction_id() != &observed.provenance.extraction_id {
            return Err("an observation does not match its provenance".into());
        }
    }
    Ok(())
}

impl BusinessDetail {
    /// The detail must describe the requested business, and only it.
    pub fn validate(&self, requested: &Id) -> Result<(), String> {
        let id = &self.business.id;
        if id != requested {
            return Err(format!("asked for business {requested}, received {id}"));
        }
        check_observations(id, &self.names)?;
        check_observations(id, &self.locations)?;
        check_observations(id, &self.websites)?;
        check_observations(id, &self.contacts)?;
        check_observations(id, &self.classifications)?;
        check_observations(id, &self.evidence)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn ids_must_be_canonical_uuids() {
        assert!(Id::parse("01900000-0000-7000-8000-000000000001").is_ok());
        for bad in [
            "",
            "not-a-uuid",
            "01900000-0000-7000-8000-00000000000G",
            "01900000-0000-7000-8000-00000000000A", // upper case
            "0190000000007000800000000000000a",     // no hyphens
        ] {
            assert!(Id::parse(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn timestamps_must_be_utc_with_milliseconds() {
        assert!(UtcTimestamp::parse("2026-01-01T00:00:00.000Z").is_ok());
        for bad in [
            "2026-01-01T00:00:00Z",
            "2026-01-01T00:00:00.000+02:00",
            "2026-01-01 00:00:00.000Z",
            "2026-02-30T00:00:00.000Z",
            "yesterday",
        ] {
            assert!(UtcTimestamp::parse(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn confidence_and_cursor_are_bounded() {
        assert!(serde_json::from_value::<Confidence>(json!(0.5)).is_ok());
        assert!(serde_json::from_value::<Confidence>(json!(1.5)).is_err());
        assert!(serde_json::from_value::<Confidence>(json!(-0.1)).is_err());
        assert!(serde_json::from_value::<Cursor>(json!("WyJuYW1lIl0")).is_ok());
        assert!(serde_json::from_value::<Cursor>(json!("has spaces")).is_err());
        assert!(serde_json::from_value::<Cursor>(json!("x".repeat(3000))).is_err());
    }

    fn query() -> BusinessListQuery {
        serde_json::from_value(json!({
            "project_id": null, "search": null, "status": null, "sort": "name",
            "limit": 2, "cursor": null
        }))
        .expect("valid query")
    }

    #[test]
    fn queries_are_validated_before_reaching_the_worker() {
        assert!(query().validate().is_ok());
        let mut too_big = query();
        too_big.limit = MAX_PAGE_SIZE + 1;
        assert!(too_big.validate().is_err());
        let mut zero = query();
        zero.limit = 0;
        assert!(zero.validate().is_err());
        let mut long_search = query();
        long_search.search = Some("x".repeat(201));
        assert!(long_search.validate().is_err());
        let unknown = json!({
            "project_id": null, "search": null, "status": "bogus", "sort": "name",
            "limit": 2, "cursor": null
        });
        assert!(serde_json::from_value::<BusinessListQuery>(unknown).is_err());
    }

    #[test]
    fn pages_that_do_not_match_their_query_are_refused() {
        let item = |status: &str| {
            json!({
                "id": "01900000-0000-7000-8000-000000000002",
                "project_id": "01900000-0000-7000-8000-000000000001",
                "display_name": "Synthetic", "status": status, "lead_stage": "not_contacted",
                "locality": null, "region": null, "primary_domain": null, "primary_phone": null,
                "primary_category": null, "source_count": 1, "evidence_count": 0,
                "last_seen_at": "2026-01-01T00:00:00.000Z", "is_synthetic": true
            })
        };
        let page = |items: Vec<Value>, total: u64, cursor: Option<&str>| -> BusinessPage {
            serde_json::from_value(json!({"items": items, "next_cursor": cursor, "total": total}))
                .expect("valid page")
        };
        let q = query();
        assert!(page(vec![item("candidate")], 1, None).validate(&q).is_ok());
        let three = vec![item("candidate"), item("candidate"), item("candidate")];
        assert!(page(three, 3, None).validate(&q).is_err()); // over the limit
        assert!(page(vec![item("candidate")], 0, None).validate(&q).is_err()); // total too low
        assert!(
            page(vec![item("candidate")], 5, Some("abc"))
                .validate(&q)
                .is_err()
        );
        let mut filtered = q.clone();
        filtered.status = Some(BusinessStatus::Active);
        assert!(
            page(vec![item("candidate")], 1, None)
                .validate(&filtered)
                .is_err()
        );
    }
}
