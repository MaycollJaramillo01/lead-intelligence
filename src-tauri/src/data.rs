fn check_page(len: usize, total: u64, has_more: bool, limit: u32) -> Result<(), String> {
    if len > limit as usize {
        return Err(format!("page has {len} rows but the limit was {limit}"));
    }
    if (len as u64) > total {
        return Err(format!(
            "page has {len} rows but reports a total of {total}"
        ));
    }
    if has_more && len < limit as usize {
        return Err("a partial page cannot have a next cursor".into());
    }
    Ok(())
}

impl BusinessPage {
    /// Checks the worker's answer against the query that produced it.
    pub fn validate(&self, query: &BusinessListQuery) -> Result<(), String> {
        check_page(
            self.items.len(),
            self.total,
            self.next_cursor.is_some(),
            query.limit,
        )?;
        if let Some(project) = &query.project_id
            && let Some(other) = self.items.iter().find(|item| &item.project_id != project)
        {
            return Err(format!("business {} belongs to another project", other.id));
        }
        if query
            .status
            .is_some_and(|status| self.items.iter().any(|item| item.status != status))
        {
            return Err("page contains businesses outside the status filter".into());
        }
        // a Latino filter is a claim about every row it lets through (phase 07)
        let outside = self.items.iter().find(|item| {
            query
                .latino_status
                .is_some_and(|status| item.latino_status != status)
                || query
                    .latino_min_confidence
                    .is_some_and(|min| item.latino_confidence.map_or(0.0, |value| value.0) < min.0)
                || query.latino_review.is_some_and(|review| {
                    item.latino_reviewed == (review == LatinoReviewFilter::Unreviewed)
                })
        });
        match outside {
            Some(item) => Err(format!(
                "business {} does not match the Latino evidence filters",
                item.id
            )),
            None => Ok(()),
        }
    }
}

impl DatasetPage {
    pub fn validate(&self, query: &DatasetListQuery) -> Result<(), String> {
        check_page(
            self.items.len(),
            self.total,
            self.next_cursor.is_some(),
            query.limit,
        )
    }
}

fn check_observations<T: Observation>(
    members: &[&Id],
    group: &[Observed<T>],
    seen: &mut HashSet<Id>,
) -> Result<(), String> {
    for observed in group {
        if !members.contains(&observed.value.business_id()) {
            return Err(format!(
                "an observation of business {} does not belong to this business",
                observed.value.business_id()
            ));
        }
        if observed.value.extraction_id() != &observed.provenance.extraction_id {
            return Err("an observation does not match its provenance".into());
        }
        seen.insert(observed.value.id().clone());
    }
    Ok(())
}

impl BusinessDetail {
    /// The detail must describe the requested business: its observations belong to it or to the
    /// records merged into it, and every value it shows points at one of those observations.
    pub fn validate(&self, requested: &Id) -> Result<(), String> {
        let id = &self.business.id;
        if id != requested {
            return Err(format!("asked for business {requested}, received {id}"));
        }
        let members: Vec<&Id> = self
            .members
            .iter()
            .map(|member| &member.business_id)
            .collect();
        if !members.contains(&id) {
            return Err("a business must be one of its own members".into());
        }
        if self.business.status == BusinessStatus::Merged && members.len() != 1 {
            return Err("a merged record cannot have records of its own".into());
        }
        let mut seen = HashSet::new();
        check_observations(&members, &self.names, &mut seen)?;
        check_observations(&members, &self.locations, &mut seen)?;
        check_observations(&members, &self.websites, &mut seen)?;
        check_observations(&members, &self.contacts, &mut seen)?;
        check_observations(&members, &self.classifications, &mut seen)?;
        check_observations(&members, &self.evidence, &mut seen)?;
        for value in &self.canonical {
            if &value.business_id != id {
                return Err(format!(
                    "canonical value {} belongs to another business",
                    value.id
                ));
            }
            if !seen.contains(&value.observation_id) {
                return Err(format!(
                    "canonical value {} points at an observation this business does not hold",
                    value.id
                ));
            }
        }
        Ok(())
    }
}

