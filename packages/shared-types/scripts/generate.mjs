// Generates src/contracts.ts from schema/contracts.schema.json (itself exported from Pydantic).
//   node scripts/generate.mjs          write the file
//   node scripts/generate.mjs --check  exit 1 when the committed file is stale
import { readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";

const schemaUrl = new URL("../schema/contracts.schema.json", import.meta.url);
const outUrl = new URL("../src/contracts.ts", import.meta.url);

const schema = JSON.parse(await readFile(schemaUrl, "utf8"));
const generated = await compile(schema, "LeadIntelligenceContracts", {
  bannerComment:
    "/* Generated by packages/shared-types/scripts/generate.mjs from schema/contracts.schema.json.\n" +
    " * Source of truth: services/research-engine/src/research_engine/contracts.py. Do not edit. */",
  unreachableDefinitions: true,
  additionalProperties: false,
  strictIndexSignatures: true,
  style: { printWidth: 100 },
});

if (process.argv.includes("--check")) {
  const current = await readFile(outUrl, "utf8").catch(() => "");
  if (current.replace(/\r\n/g, "\n") !== generated) {
    console.error("packages/shared-types/src/contracts.ts is stale; run `pnpm contracts`");
    process.exit(1);
  }
} else {
  await writeFile(outUrl, generated);
  console.log("wrote src/contracts.ts");
}
